CREATE TABLE IF NOT EXISTS orgs (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(200) NOT NULL,
  email VARCHAR(200) NOT NULL UNIQUE,
  pw_hash VARCHAR(200) NOT NULL,
  pw_salt VARCHAR(100) NOT NULL,
  assistant_token VARCHAR(100) NOT NULL UNIQUE,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS sessions (
  token_hash VARCHAR(100) PRIMARY KEY,
  org_id BIGINT NOT NULL,
  expires_at BIGINT NOT NULL,
  FOREIGN KEY (org_id) REFERENCES orgs(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS documents (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  org_id BIGINT NOT NULL,
  filename VARCHAR(300) NOT NULL,
  pages INT NOT NULL,
  size_bytes BIGINT NOT NULL,
  stored_path VARCHAR(600) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (org_id) REFERENCES orgs(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_docs_org ON documents(org_id);

CREATE TABLE IF NOT EXISTS chunks (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  org_id BIGINT NOT NULL,
  doc_id BIGINT NOT NULL,
  page_no INT NOT NULL,
  heading VARCHAR(500) NOT NULL,
  body CLOB NOT NULL,
  FOREIGN KEY (org_id) REFERENCES orgs(id) ON DELETE CASCADE,
  FOREIGN KEY (doc_id) REFERENCES documents(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_chunks_org ON chunks(org_id);

CREATE TABLE IF NOT EXISTS org_usage (
  org_id BIGINT PRIMARY KEY,
  asked INT DEFAULT 0 NOT NULL,
  answered INT DEFAULT 0 NOT NULL,
  unable INT DEFAULT 0 NOT NULL,
  errors INT DEFAULT 0 NOT NULL,
  FOREIGN KEY (org_id) REFERENCES orgs(id) ON DELETE CASCADE
);
